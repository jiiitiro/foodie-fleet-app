-- Hibernate runs with ddl-auto=validate. Never edit this file once applied: add V2__..., V3__... instead.

CREATE TABLE users (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email        VARCHAR(255) NOT NULL,
    password     VARCHAR(255) NOT NULL,
    full_name    VARCHAR(255) NOT NULL,
    phone_number VARCHAR(255),
    role         VARCHAR(32)  NOT NULL,
    enabled      BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMP(6),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('CUSTOMER', 'RESTAURANT_OWNER', 'DRIVER', 'ADMIN'))
);

CREATE TABLE verification_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token       VARCHAR(255) NOT NULL,
    user_id     BIGINT       NOT NULL,
    expiry_date TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_verification_tokens_token UNIQUE (token),
    CONSTRAINT uk_verification_tokens_user UNIQUE (user_id),
    CONSTRAINT fk_verification_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE restaurants (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id    BIGINT       NOT NULL,
    name        VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    address     VARCHAR(255) NOT NULL,
    phone       VARCHAR(255),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_restaurants_owner UNIQUE (owner_id),
    CONSTRAINT fk_restaurants_owner FOREIGN KEY (owner_id) REFERENCES users (id)
);

CREATE TABLE menu_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT        NOT NULL,
    name          VARCHAR(255)  NOT NULL,
    description   VARCHAR(255),
    price         NUMERIC(10, 2) NOT NULL,
    available     BOOLEAN       NOT NULL DEFAULT TRUE,
    image_url     VARCHAR(255),
    CONSTRAINT ck_menu_items_price CHECK (price >= 0),
    CONSTRAINT fk_menu_items_restaurant FOREIGN KEY (restaurant_id) REFERENCES restaurants (id)
);

CREATE INDEX ix_menu_items_restaurant ON menu_items (restaurant_id);

CREATE TABLE orders (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      BIGINT         NOT NULL,
    restaurant_id    BIGINT         NOT NULL,
    driver_id        BIGINT,
    status           VARCHAR(32)    NOT NULL,
    total_price      NUMERIC(10, 2) NOT NULL,
    delivery_address VARCHAR(255)   NOT NULL,
    created_at       TIMESTAMP(6),
    CONSTRAINT ck_orders_status CHECK (status IN ('PLACED', 'ACCEPTED', 'PREPARING', 'READY_FOR_PICKUP',
                                                  'OUT_FOR_DELIVERY', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES users (id),
    CONSTRAINT fk_orders_restaurant FOREIGN KEY (restaurant_id) REFERENCES restaurants (id),
    CONSTRAINT fk_orders_driver FOREIGN KEY (driver_id) REFERENCES users (id)
);

CREATE INDEX ix_orders_customer ON orders (customer_id);
CREATE INDEX ix_orders_restaurant ON orders (restaurant_id);
CREATE INDEX ix_orders_driver ON orders (driver_id);
CREATE INDEX ix_orders_status ON orders (status);

CREATE TABLE order_items (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id          BIGINT         NOT NULL,
    menu_item_id      BIGINT         NOT NULL,
    quantity          INTEGER        NOT NULL,
    price_at_purchase NUMERIC(10, 2) NOT NULL,
    CONSTRAINT ck_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_order_items_menu_item FOREIGN KEY (menu_item_id) REFERENCES menu_items (id)
);

CREATE INDEX ix_order_items_order ON order_items (order_id);
